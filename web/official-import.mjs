// Native MiniMax H3 adapter. No Director editor or Python dependency required.
export function isOfficialTarget(node) {
    return (node?.comfyClass || node?.type) === 'MiniMaxH3ReferenceToVideo';
}

function officialTagRegex(tag,label) {
    return new RegExp(`<\\s*${tag}\\s+(\\d+)\\s*>|@${label}(\\d+)(?:\\.(?:png|jpe?g|webp|wav|mp3|flac|ogg|m4a|aac|mp4|mov|webm|mkv))?`,'gi');
}

export function planOfficialGroup(chapter, groupIndex, fps=24) {
    const group=chapter?.groups?.[groupIndex];
    if (!group) throw Error('请选择要导入的素材组');
    if (!Number.isFinite(fps) || fps<=0) throw Error('官方工作流帧率无效');
    const seconds=Number(group.seconds);
    if (!Number.isFinite(seconds) || seconds<=0 || seconds>20.7) throw Error('素材组时长无效');
    let prompt=group.prompt;
    const result={groupNumber:group.number,seconds,fps,images:[],audios:[],videos:[],mapping:{}};
    for(const [key,tag,label,files,limit,defaultAll] of [
        ['images','Picture','图片',chapter.sharedImages || group.images || [],9,true],
        ['audios','Audio','音频',chapter.sharedAudios || group.audios || [],3,false],
        ['videos','Video','视频',chapter.sharedVideos || group.videos || [],3,false],
    ]) {
        let wanted=[...new Set([...prompt.matchAll(officialTagRegex(tag,label))].map(m=>Number(m[1]||m[2])))].sort((a,b)=>a-b);
        if (!wanted.length && defaultAll) wanted=files.map((_,i)=>i+1);
        if (wanted.length>limit) throw Error(`官方节点单组最多${limit}份${label}，请减少该组引用`);
        if (wanted.some(n=>n<1||n>files.length)) throw Error(`该组引用的公共${label}不存在`);
        const mapping=new Map(wanted.map((n,i)=>[n,i+1]));
        result[key]=wanted.map(n=>files[n-1]);
        result.mapping[tag]=Object.fromEntries(mapping);
        prompt=prompt.replace(officialTagRegex(tag,label),(_,a,b)=>`<${tag} ${mapping.get(Number(a||b))}>`);
    }
    result.prompt=prompt;
    const n=Math.max(5,Math.round(seconds*fps));
    result.length=n+(5-n%17+17)%17;
    return result;
}

const officialRefInput=name=>/^(?:ref_images\.ref_image_|ref_videos\.ref_video_|ref_video_audios\.ref_video_audio_|ref_audios\.ref_audio_|ref_image_|ref_video_audio_|ref_video_|ref_audio_)/.test(name);

export function officialGraphSignature(graph) {
    return JSON.stringify({nodes:graph.nodes.map(n=>[n.id,n.type,n.mode,n.widgets_values,n.pos,n.inputs]),links:graph.links});
}

export function buildOfficialImport(before, targetId, plan, uploaded, makeLoader) {
    const graph=structuredClone(before);
    const target=graph.nodes.find(n=>String(n.id)===String(targetId));
    if (!isOfficialTarget(target)) throw Error('找不到官方 MiniMax H3 Reference to Video 节点');
    if (!Array.isArray(graph.links) || graph.links.some(link=>!Array.isArray(link))) throw Error('暂不支持此工作流连线格式，请导出常规工作流JSON后重试');
    if (!Array.isArray(target.widgets_values) || target.widgets_values.length<5) throw Error('官方节点参数结构不兼容');
    for(const kind of ['images','audios','videos']) {
        if ((uploaded[kind] || []).length!==plan[kind].length) throw Error(`${kind}上传结果不完整`);
    }
    const removeLink=id=>{
        const link=graph.links.find(row=>row[0]===id);
        if (!link) return;
        const source=graph.nodes.find(n=>n.id===link[1]);
        const dest=graph.nodes.find(n=>n.id===link[3]);
        if (source?.outputs?.[link[2]]) source.outputs[link[2]].links=(source.outputs[link[2]].links || []).filter(value=>value!==id);
        if (dest?.inputs?.[link[4]]) dest.inputs[link[4]].link=null;
        graph.links=graph.links.filter(row=>row[0]!==id);
    };
    // Remove only nodes generated by a previous import into this exact target.
    const prior=graph.nodes.filter(n=>String(n.properties?.localOfficialImportTargetId)===String(targetId));
    for(const node of prior) {
        for(const link of [...graph.links]) if(link[1]===node.id||link[3]===node.id) removeLink(link[0]);
        graph.nodes=graph.nodes.filter(n=>n.id!==node.id);
    }
    for(const input of target.inputs || []) {
        if ((officialRefInput(input.name)||['prompt','length'].includes(input.name)) && input.link!=null) removeLink(input.link);
    }
    target.widgets_values[0]=plan.prompt;
    target.widgets_values[3]=plan.length;
    if(target.widgets_values_named) Object.assign(target.widgets_values_named,{prompt:plan.prompt,length:plan.length});
    let nodeId=Math.max(Number(graph.last_node_id)||0,...graph.nodes.map(n=>Number(n.id)||0));
    let linkId=Math.max(Number(graph.last_link_id)||0,...graph.links.map(link=>Number(link[0])||0));
    let row=0;
    const add=(type,file,title)=>{
        const node=structuredClone(makeLoader(type,file));
        if (!node || node.type!==type) throw Error(`当前ComfyUI缺少${type}节点`);
        node.id=++nodeId;node.mode=0;node.title=title;
        node.pos=[Number(target.pos?.[0]||0)-800,Number(target.pos?.[1]||0)+row++*350];
        node.properties={...node.properties,localOfficialImportTargetId:targetId};
        for(const input of node.inputs || []) input.link=null;
        for(const output of node.outputs || []) output.links=[];
        graph.nodes.push(node);
        return node;
    };
    const connect=(source,type,dest,name)=>{
        const out=source.outputs.findIndex(output=>output.type===type);
        if(out<0) throw Error(`${source.type}缺少${type}输出`);
        let slot=dest.inputs.findIndex(input=>input.name===name);
        if(slot<0) {
            if(dest!==target) throw Error(`${dest.type}缺少${name}输入`);
            dest.inputs.push({name,label:name.split('.').at(-1),type,shape:7,link:null});slot=dest.inputs.length-1;
        }
        const id=++linkId;
        source.outputs[out].links ||= [];source.outputs[out].links.push(id);
        dest.inputs[slot].link=id;graph.links.push([id,source.id,out,dest.id,slot,type]);
    };
    connect(add('PrimitiveStringMultiline',plan.prompt,`素材组${plan.groupNumber} · 提示词`),'STRING',target,'prompt');
    connect(add('PrimitiveInt',plan.length,`素材组${plan.groupNumber} · ${plan.seconds}秒 / ${plan.length}帧`),'INT',target,'length');
    uploaded.images.forEach((file,i)=>connect(add('LoadImage',file,`素材组${plan.groupNumber} · 图片${i+1}`),'IMAGE',target,`ref_images.ref_image_${i}`));
    uploaded.audios.forEach((file,i)=>connect(add('LoadAudio',file,`素材组${plan.groupNumber} · 音频${i+1}`),'AUDIO',target,`ref_audios.ref_audio_${i}`));
    uploaded.videos.forEach((file,i)=>{
        const loader=add('LoadVideo',file,`素材组${plan.groupNumber} · 视频${i+1}`);
        const components=add('GetVideoComponents',null,`视频${i+1} · 提取画面`);
        connect(loader,'VIDEO',components,'video');
        connect(components,'IMAGE',target,`ref_videos.ref_video_${i}`);
        // Video soundtracks are intentionally not additional voice references.
    });
    graph.last_node_id=nodeId;graph.last_link_id=linkId;
    return {graph,targetId,plan,uploaded};
}

export function verifyOfficialImport(actual, expected) {
    const target=actual.nodes.find(n=>String(n.id)===String(expected.targetId));
    if (!target || target.widgets_values[0]!==expected.plan.prompt || target.widgets_values[3]!==expected.plan.length) throw Error('官方节点提示词或时长回读不符');
    const inputFile=name=>{
        const input=target.inputs.find(row=>row.name===name);
        const link=actual.links.find(row=>row[0]===input?.link);
        const source=actual.nodes.find(n=>n.id===link?.[1]);
        if(source?.type==='GetVideoComponents') {
            const videoLink=actual.links.find(row=>row[0]===source.inputs.find(i=>i.name==='video')?.link);
            return actual.nodes.find(n=>n.id===videoLink?.[1])?.widgets_values?.[0];
        }
        return source?.widgets_values?.[0];
    };
    if(inputFile('prompt')!==expected.plan.prompt || inputFile('length')!==expected.plan.length) throw Error('官方提示词或帧数输入连线回读不符');
    for(const [key,prefix] of [['images','ref_images.ref_image_'],['audios','ref_audios.ref_audio_'],['videos','ref_videos.ref_video_']]) {
        expected.uploaded[key].forEach((file,i)=>{
            if(inputFile(prefix+i)!==file) throw Error(`官方${key}槽位${i+1}文件回读不符`);
        });
    }
    const expectedInputs=expected.graph.nodes.find(n=>String(n.id)===String(expected.targetId)).inputs;
    for(const input of target.inputs.filter(i=>officialRefInput(i.name)&&i.link!=null)) {
        if (!expectedInputs.some(i=>i.name===input.name&&i.link!=null)) throw Error('官方节点仍残留未选择的参考输入');
    }
    for(const node of expected.graph.nodes) {
        if(String(node.id)===String(expected.targetId)||node.properties?.localOfficialImportTargetId!=null) continue;
        const current=actual.nodes.find(n=>n.id===node.id);
        if(!current || JSON.stringify(current.widgets_values)!==JSON.stringify(node.widgets_values) || current.mode!==node.mode) throw Error('原有模型或采样节点参数发生变化');
    }
}

export async function applyOfficialImport(app, expected, before) {
    try {
        await app.loadGraphData(structuredClone(expected.graph));
        verifyOfficialImport(app.graph.serialize(),expected);
        app.graph.setDirtyCanvas?.(true,true);
    } catch(error) {
        try {await app.loadGraphData(structuredClone(before));}
        catch(rollback) {throw Error(error.message+'；恢复失败：'+rollback.message);}
        throw error;
    }
}
