import assert from 'node:assert/strict';
import '../web/folder-core.js';
const f=(name,text='')=>({name:name.split('/').at(-1),webkitRelativePath:name,text:async()=>text});
const parse=globalThis.H3FolderCore.parseFiles;
const group=(page)=>[f(`${page}/素材组1/提示词.txt`,'integrated_multimodal_description: <Picture 1> 女人站在窗边。\noverall_soundscape: 风声。\nnon_diegetic_music: N/A'),f(`${page}/公共参考图/@图片1.png`)];
const parent='01_一碗热饭',child=parent+'/01_一碗热饭_01';
const index='|素材组|请求秒数|提示词|\n|---|---|---|\n|素材组1|5|素材组1/提示词.txt|';
const screenshot=await parse([...group(child),f(parent+'/素材索引.md',index)]);
assert.equal(screenshot[0].name,child);assert.equal(screenshot[0].groups[0].seconds,5);
const local=await parse([...group(child),f(child+'/素材索引.md',index)]);assert.equal(local[0].groups[0].seconds,5);
const old=await parse([...group(child),f(child+'/素材组索引.md',index)]);assert.equal(old[0].groups[0].seconds,5);
await assert.rejects(()=>parse([...group(child),...group(parent+'/01_一碗热饭_02'),f(parent+'/素材索引.md',index)]),/无法识别/);
await assert.rejects(()=>parse([...group(child),f(child+'/素材索引.md',index),f(child+'/素材组索引.md',index.replace('|5|','|6|'))]),/内容不同/);
await assert.rejects(()=>parse([f(parent+'/素材索引.md',index)]),/未找到素材组/);
const auto=[f(child+'/素材组1/提示词.txt','0.0～4.0秒：知夏(S3)，黑发成年女性。')];
await assert.rejects(()=>parse(auto),/参考图数量/);assert.equal((await parse(auto,{allowNoImages:true}))[0].groups[0].seconds,4);
console.log('PASS screenshot-style arbitrary folder names, 素材索引 alias, single-page outer index, multi-page ambiguity rejection, index conflicts and mode-specific missing-image validation');
