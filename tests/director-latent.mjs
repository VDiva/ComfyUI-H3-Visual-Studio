import assert from 'node:assert/strict';
import fs from 'node:fs';
import {finishApi,defaultFinishing,LATENT_MODEL} from '../web/finishing.mjs';
import {modelReport} from '../web/model-check.mjs';
const base=JSON.parse(fs.readFileSync(new URL('../examples/官方采样API基线.json',import.meta.url),'utf8'));
const nodes=(p,type)=>Object.entries(p).filter(([,n])=>n.class_type===type);
const p=finishApi(structuredClone(base),{...defaultFinishing(),passes:2},864,480);
const [[liftId,lift]]=nodes(p,'H3DirectorLatentUpscale');
assert.equal(lift.inputs.model_name,LATENT_MODEL);assert.equal(lift.inputs.width,1344);assert.equal(lift.inputs.height,736);
assert.equal(nodes(p,'H3FrameUpscale').length,0);
const samplers=nodes(p,'SamplerCustomAdvanced');assert.equal(samplers.length,3);
const refiners=samplers.filter(([,n])=>p[n.inputs.guider[0]].inputs.conditioning?.[0]===liftId);
assert.equal(refiners.length,2);assert.deepEqual(refiners[0][1].inputs.latent_image,[liftId,0]);
assert.deepEqual(refiners[1][1].inputs.latent_image,[refiners[0][0],0]);
assert.equal(p[refiners[0][1].inputs.sampler[0]].inputs.sampler_name,'euler');
assert.equal(p[refiners[0][1].inputs.sigmas[0]].inputs.denoise,0.15);
const original=nodes(p,'SaveVideo').find(([,n])=>n.inputs.filename_prefix.includes('_original'));
const preserved=p[lift.inputs.samples[0]];assert.equal(preserved.class_type,'H3PreserveLatent');assert.deepEqual(preserved.inputs.saved_video,[original[0],0]);
const videos=nodes(p,'CreateVideo');assert.deepEqual(videos[0][1].inputs.audio,videos[1][1].inputs.audio);
assert.deepEqual(base[Object.keys(base).find(id=>base[id].class_type==='VAEDecode')].inputs.samples,preserved.inputs.samples);
const only=finishApi(structuredClone(base),{...defaultFinishing(),refine:false},864,480);
assert.equal(nodes(only,'SamplerCustomAdvanced').length,1);assert.equal(nodes(only,'H3DirectorLatentUpscale').length,1);
const report=modelReport({H3DirectorLatentUpscale:{input:{required:{model_name:['COMBO',{options:[]}]}}}},[{'1':lift}]);
assert.deepEqual(report.missing,['models/latent_upscale_models/'+LATENT_MODEL]);
assert.throws(()=>finishApi(structuredClone(base),{...defaultFinishing(),megapixels:0.1},864,480),/目标小于/);
console.log('PASS Director lift-before-refine, resized conditioning, pass chain, original retention, audio identity, latent-only and missing weights');
